// Renders an ordered sequence of steps as connected boxes — a flowchart —
// using native vector shapes (no external image/diagram service needed).
// Wraps into multiple rows of up to 4 boxes if there are many steps.
function addFlowchartSlide(ppt, title, steps, page, total) {
    const slide = ppt.addSlide();
    slide.background = { color: COLORS.white };

    addSlideHeader(slide, ppt, title)

    const safeSteps = (steps || []).filter(Boolean).slice(0, 8)
    const maxPerRow = 4
    const rows = []
    for (let i = 0; i < safeSteps.length; i += maxPerRow) {
        rows.push(safeSteps.slice(i, i + maxPerRow))
    }

    const areaX = 0.6
    const areaW = 12
    const boxH = 1.1
    const rowGap = 0.9
    const startY = 1.6

    rows.forEach((row, rowIndex) => {
        const n = row.length
        const slotW = areaW / n
        const boxW = slotW - 0.5
        const y = startY + rowIndex * (boxH + rowGap)

        row.forEach((stepText, i) => {
            const x = areaX + i * slotW + (slotW - boxW) / 2
            const globalIndex = rowIndex * maxPerRow + i
            const stepColor = FLOWCHART_PALETTE[globalIndex % FLOWCHART_PALETTE.length]

            slide.addShape(ppt.ShapeType.roundRect, {
                x,
                y,
                w: boxW,
                h: boxH,
                fill: { color: stepColor.fill },
                line: { color: stepColor.stroke, width: 1.5 },
                radius: 0.1,
            })

            slide.addText(String(stepText), {
                x: x + 0.1,
                y: y + 0.1,
                w: boxW - 0.2,
                h: boxH - 0.2,
                align: "center",
                valign: "middle",
                fontSize: 13,
                color: COLORS.text,
                bold: true,
                fit: "shrink",
            })

            // Arrow to the next box in the same row (documented pptxgenjs
            // pattern: a horizontal LINE shape with endArrowType). Colored
            // to match the box it's leaving, for a flowing look.
            if (i < n - 1) {
                slide.addShape(ppt.ShapeType.line, {
                    x: x + boxW,
                    y: y + boxH / 2,
                    w: slotW - boxW,
                    h: 0,
                    line: { color: stepColor.stroke, width: 2, endArrowType: "triangle" },
                })
            }
        })

        // Connector down to the next row. Using a thin filled rectangle
        // instead of a vertical line shape — pptxgenjs draws zero-width
        // vertical lines at an angle in some versions, a rect avoids that.
        if (rowIndex < rows.length - 1) {
            const lastGlobalIndex = rowIndex * maxPerRow + (n - 1)
            const lastColor = FLOWCHART_PALETTE[lastGlobalIndex % FLOWCHART_PALETTE.length]
            const lastCenterX = areaX + (n - 1) * slotW + slotW / 2
            slide.addShape(ppt.ShapeType.rect, {
                x: lastCenterX - 0.02,
                y: y + boxH,
                w: 0.04,
                h: rowGap,
                fill: { color: lastColor.stroke },
                line: { color: lastColor.stroke },
            })
        }
    })

    addSlideFooter(slide, page, total)
}

// Embeds a locally-stored image (user-uploaded) onto its own slide.
function addImageSlide(ppt, title, imagePath, page, total) {
    const slide = ppt.addSlide();
    slide.background = { color: COLORS.white };

    addSlideHeader(slide, ppt, title || "Image")

    if (imagePath) {
        slide.addImage({
            path: imagePath,
            x: 1.5,
            y: 1.3,
            w: 10.33,
            h: 5.3,
            sizing: { type: "contain", w: 10.33, h: 5.3 },
        })
    }

    addSlideFooter(slide, page, total)
}