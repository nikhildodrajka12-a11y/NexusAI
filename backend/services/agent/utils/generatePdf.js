import PDFDocument from "pdfkit"

// A distinct fill/stroke pair per flowchart step, cycled through so every
// box in a chain gets its own color instead of one flat blue tone.
const FLOWCHART_PALETTE = [
    { fill: "#DBEAFE", stroke: "#2563EB" }, // blue
    { fill: "#D1FAE5", stroke: "#059669" }, // green
    { fill: "#FEF3C7", stroke: "#D97706" }, // amber
    { fill: "#EDE9FE", stroke: "#7C3AED" }, // purple
    { fill: "#FCE7F3", stroke: "#DB2777" }, // pink
    { fill: "#CCFBF1", stroke: "#0D9488" }, // teal
    { fill: "#FEE2E2", stroke: "#DC2626" }, // red
]

export const generatePdf = async (data) => {
    return new Promise((resolve, reject) => {
        const doc = new PDFDocument({
            size: "A4",
            margin: 50,
            info: {
                Author: "NexusAI",
                Title: data.title,
                Creator: "NexusAI"
            }
        })

        const chunks = []

        doc.on("data", (chunk) => chunks.push(chunk))
        doc.on("end", () => resolve(Buffer.concat(chunks)))
        doc.on("error", () => reject)

        // title
        doc
            .fontSize(28)
            .text(data.title, { align: "center" })
            .fillColor("#111827")

        if (data.subtitle) {
            doc.moveDown(0.5)
        }

        // subtitle
        doc
            .fontSize(12)
            .text(data.subtitle, { align: "center" })
            .fillColor("#6B7280")

        doc.moveDown(2)

        // sections
        data?.sections?.forEach((s) => {
            if (s.type === "flowchart") {
                addFlowchartSection(doc, s.heading, s.steps || [])
            } else if (s.type === "image") {
                addImageSection(doc, s.heading, s.imagePath)
            } else {
                addBulletSection(doc, s.heading, s.points || [])
            }
        })

        // footer
        doc.moveDown()

        doc
            .fontSize(10)
            .text("Generated By NexusAI", { align: "center" })
            .fillColor("#9CA3AF")

        doc.end()
    })
}

function addBulletSection(doc, heading, points) {
    doc
        .fontSize(18)
        .text(heading)
        .fillColor("#111827")

    doc.moveDown(0.5)

    points?.forEach((p) => {
        doc
            .fontSize(12)
            .text("• " + p, { lineGap: 5 })
            .fillColor("#374151")
    })

    doc.moveDown()
}

// Renders an ordered sequence of steps as connected boxes — a flowchart —
// using pdfkit's native vector drawing (rect + line + polygon for the
// arrowhead). No external image/diagram service needed.
function addFlowchartSection(doc, heading, steps) {
    doc.addPage()

    doc
        .fontSize(20)
        .fillColor("#111827")
        .text(heading || "Flowchart")

    doc.moveDown(1)

    const safeSteps = (steps || []).filter(Boolean).slice(0, 8)
    const maxPerRow = 3
    const rows = []
    for (let i = 0; i < safeSteps.length; i += maxPerRow) {
        rows.push(safeSteps.slice(i, i + maxPerRow))
    }

    const marginX = doc.page.margins.left
    const usableWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right
    const boxH = 60
    const rowGap = 45
    let y = doc.y + 10

    rows.forEach((row, rowIndex) => {
        const n = row.length
        const slotW = usableWidth / n
        const boxW = slotW - 30

        row.forEach((stepText, i) => {
            const x = marginX + i * slotW + (slotW - boxW) / 2
            const globalIndex = rowIndex * maxPerRow + i
            const stepColor = FLOWCHART_PALETTE[globalIndex % FLOWCHART_PALETTE.length]

            doc
                .roundedRect(x, y, boxW, boxH, 8)
                .fillAndStroke(stepColor.fill, stepColor.stroke)

            doc
                .fillColor("#111827")
                .fontSize(11)
                .text(String(stepText), x + 8, y + boxH / 2 - 6, {
                    width: boxW - 16,
                    align: "center",
                })

            if (i < n - 1) {
                const arrowY = y + boxH / 2
                const startX = x + boxW
                const endX = startX + (slotW - boxW)

                doc
                    .moveTo(startX, arrowY)
                    .lineTo(endX - 8, arrowY)
                    .lineWidth(2)
                    .stroke(stepColor.stroke)

                doc
                    .polygon([endX, arrowY], [endX - 10, arrowY - 5], [endX - 10, arrowY + 5])
                    .fill(stepColor.stroke)
            }
        })

        y += boxH + rowGap
    })

    doc.y = y + 10
}

// Embeds a locally-stored image (user-uploaded or AI-generated) on its own
// page.
function addImageSection(doc, heading, imagePath) {
    doc.addPage()

    doc
        .fontSize(20)
        .fillColor("#111827")
        .text(heading || "Image")

    doc.moveDown(1)

    if (imagePath) {
        const usableWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right

        doc.image(imagePath, doc.page.margins.left, doc.y, {
            fit: [usableWidth, 500],
            align: "center",
        })
    }
}