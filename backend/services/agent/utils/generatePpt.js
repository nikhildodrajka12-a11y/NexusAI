import pptxgen from "pptxgenjs"

const COLORS = {
    primary: "2563EB",
    secondary: "0F172A",
    text: "334155",
    light: "F8FAFC",
    border: "E2E8F0",
    white: "FFFFFF",
    muted: "64748B",
};

// A distinct fill/stroke pair per flowchart step, cycled through so every
// box in a chain gets its own color instead of one flat blue tone.
const FLOWCHART_PALETTE = [
    { fill: "DBEAFE", stroke: "2563EB" }, // blue
    { fill: "D1FAE5", stroke: "059669" }, // green
    { fill: "FEF3C7", stroke: "D97706" }, // amber
    { fill: "EDE9FE", stroke: "7C3AED" }, // purple
    { fill: "FCE7F3", stroke: "DB2777" }, // pink
    { fill: "CCFBF1", stroke: "0D9488" }, // teal
    { fill: "FEE2E2", stroke: "DC2626" }, // red
]


export const generatePpt = async (data) => {
    const ppt = new pptxgen()
    ppt.layout = "LAYOUT_WIDE"
    ppt.author = "NexusAI"
    ppt.title = data.title
    ppt.subject = data.title
    ppt.company = "NexusAI"
    ppt.theme = {
        headFontFace: "Aptos",
        bodyFontFace: "Aptos"
    }




    addCover(ppt, data)

    data?.slides?.forEach((s, i) => {
        const page = i + 1
        const total = data.slides.length

        if (s.type === "flowchart") {
            addFlowchartSlide(ppt, s.title, s.steps || [], page, total)
        } else if (s.type === "image") {
            addImageSlide(ppt, s.title, s.imagePath, page, total)
        } else {
            addContentSlide(ppt, s.title, s.points || [], page, total)
        }
    });

    addThankYou(ppt)

    return ppt
}


const addCover = (ppt, data) => {
    const slide = ppt.addSlide();
    slide.background = {
        color: COLORS.primary
    }

    slide.addShape(ppt.ShapeType.rect, {
        x: 0,
        y: 0,
        w: 13.33,
        h: 0.18,
        fill: {
            color: "60A5FA"
        },
        line: {
            color: "60A5FA"
        }
    })

    slide.addText(data.title, {
        x: 0.7,
        y: 1.7,
        w: 12,
        h: 0.8,
        align: "center",
        color: COLORS.white,
        bold: true,
        fontSize: 28,
    })

    slide.addText(data.subtitle, {
        x: 1,
        y: 2.8,
        w: 11.5,
        h: 0.4,
        align: "center",
        color: "DBEAFE",
        fontSize: 15,
    })

    slide.addText("Generated By NexusAI", {
        x: 0,
        y: 6.9,
        w: 13.33,
        h: 0.2,
        align: "center",
        color: "BFDBFE",
        fontSize: 10,
    })
}

function addContentSlide(
    ppt,
    title,
    points,
    page,
    total
) {
    const slide = ppt.addSlide();

    slide.background = {
        color: COLORS.white,
    };

    slide.addText(title, {
        x: 0.6,
        y: 0.35,
        w: 10,
        h: 0.4,
        fontSize: 24,
        bold: true,
        color: COLORS.primary,
    });

    slide.addShape(ppt.ShapeType.line, {
        x: 0.6,
        y: 0.85,
        w: 12,
        h: 0,
        line: {
            color: COLORS.border,
            width: 1.2,
        },
    });

    const visiblePoints = points.slice(0, 6);

    visiblePoints.forEach((point, i) => {
        const y = 1.2 + i * 0.75;

        slide.addShape(ppt.ShapeType.roundRect, {
            x: 0.7,
            y,
            w: 12,
            h: 0.58,
            fill: {
                color: i % 2 ? "F8FAFC" : "EFF6FF",
            },
            line: {
                color: COLORS.border,
            },
            radius: 0.08,
        });

        slide.addShape(ppt.ShapeType.ellipse, {
            x: 0.92,
            y: y + 0.18,
            w: 0.12,
            h: 0.12,
            fill: {
                color: COLORS.primary,
            },
            line: {
                color: COLORS.primary,
            },
        });

        slide.addText(point, {
            x: 1.2,
            y: y + 0.08,
            w: 11,
            h: 0.35,
            fontSize: 15,
            color: COLORS.text,
            fit: "shrink",
        });
    });

    slide.addText(`${page}/${total}`, {
        x: 12.1,
        y: 6.9,
        w: 0.8,
        h: 0.2,
        align: "right",
        fontSize: 10,
        color: COLORS.muted,
    });

    slide.addText(`NexusAI`, {
        x: 0.6,
        y: 6.9,
        w: 2,
        h: 0.2,
        fontSize: 10,
        color: COLORS.muted,
    });




}


